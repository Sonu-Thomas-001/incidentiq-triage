"""Render evaluation tables (Markdown) from the recorded result JSON files.

Every number is read from docs/report/results/*.json; nothing is typed in by hand.
Usage: python -m incidentiq_ml.report_tables > docs/report/evaluation_tables.md
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parents[3] / "docs" / "report" / "results"


def _load(name: str) -> dict:
    return json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))


def _f(x, nd: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def _row(name: str, m: dict, val=None) -> str:
    topk = m.get("topk") or {}
    top1 = topk.get("top1", topk.get("1"))
    top3 = topk.get("top3", topk.get("3"))
    return (
        f"| {name} | {_f(val)} | {_f(m['macro']['f1'])} | {_f(m['weighted']['f1'])} | "
        f"{_f(m['macro']['precision'])} | {_f(m['macro']['recall'])} | {_f(m['accuracy'])} | {_f(top1)} | {_f(top3)} |"
    )


HEADER = (
    "| Model | Val macro-F1 | Test macro-F1 | Test weighted-F1 | Macro precision | Macro recall | Accuracy | Top-1 | Top-3 |\n"
    "|---|---|---|---|---|---|---|---|---|"
)


def experiment_table(name: str, title: str, note: str) -> str:
    d = _load(name)
    sp = d["split"]
    out = [
        f"### {title}",
        "",
        f"{note}",
        "",
        f"Split: {sp['strategy']} ({sp['n_train']} train / {sp['n_val']} val / {sp['n_test']} test), "
        f"{d['n_classes']} classes, seed {d['seed']}. Validation-selected: `{d['selected_by_validation']}`.",
        "",
        HEADER,
    ]
    for k, v in d["baselines"].items():
        out.append(_row(f"baseline: {k}", v["test"], v.get("val_macro_f1")))
    for k, v in d["models"].items():
        out.append(_row(k, v["test"], v.get("val_macro_f1")))
    out.append("")
    return "\n".join(out)


def per_class(name: str, model: str, title: str) -> str:
    d = _load(name)["models"][model]["test"]["per_class"]
    rows = [f"### {title}", "", "| Class | Precision | Recall | F1 | Support |", "|---|---|---|---|---|"]
    for c, m in d.items():
        rows.append(f"| {c} | {_f(m['precision'])} | {_f(m['recall'])} | {_f(m['f1'])} | {m['support']} |")
    rows.append("")
    return "\n".join(rows)


def main() -> None:
    parts = [
        "# Evaluation tables (generated)",
        "",
        "Generated by `python -m incidentiq_ml.report_tables` from `docs/report/results/*.json`. "
        "Test numbers are single held-out evaluations after validation-only tuning. "
        "**REAL-data and SYNTHETIC-demo results are in separate sections and must not be compared.**",
        "",
        "## Part I - Real public data",
        "",
        experiment_table(
            "tickets_category_real",
            "Task A: category (Zenodo tickets, REAL)",
            "Group-aware split on near-duplicate text clusters; fixed-seed; small dataset, so differences of a few points are within noise.",
        ),
        per_class(
            "tickets_category_real", "text/logreg", "Per-class test performance, deployed TF-IDF + LogReg (REAL)"
        ),
        experiment_table(
            "uci_group_real",
            "Task B: assignment group from structured opening-time fields (UCI ServiceNow log, REAL)",
            "Target is the FIRST-event assignment group (rare groups bucketed). Feature-set ablation names are in the first column.",
        ),
    ]
    pri = _load("uci_priority_real")
    pt, mb, dt = pri["policy_test"], pri["majority_baseline_test"], pri["decision_tree_on_impact_urgency_test"]
    parts += [
        "### Task C: priority (UCI ServiceNow log, REAL)",
        "",
        f"Finding: {pri['finding']}.",
        f"Policy violations: {pri['policy_violations_all_events']['violations']} of "
        f"{pri['policy_violations_all_events']['events']} events.",
        "",
        "| Method | Test macro-F1 | High-priority recall |",
        "|---|---|---|",
        f"| majority baseline | {_f(mb['macro']['f1'])} | {_f(mb['high_priority_recall'])} |",
        f"| impact x urgency policy (by construction) | {_f(pt['macro']['f1'])} | {_f(pt['high_priority_recall'])} |",
        f"| decision tree on impact, urgency | {_f(dt['macro']['f1'])} | {_f(dt['high_priority_recall'])} |",
        "",
        "The policy score is 1.0 by definition of the label, not a learned result.",
        "",
        "### Calibration and confidence routing (deployed category model, REAL)",
        "",
    ]
    cal = _load("tickets_category_real")["calibration"]
    parts += [
        f"Calibration method chosen on validation ECE: `{cal['method_selected_on_validation']}`; "
        f"validation ECE by method: {json.dumps({k: round(v, 3) for k, v in cal['validation_ece_by_method'].items()})}.",
        "",
        "| Confidence threshold | Coverage | Accuracy on covered |",
        "|---|---|---|",
    ]
    for r in cal["confidence_threshold_tradeoff"]:
        parts.append(f"| {r['threshold']} | {_f(r['coverage'])} | {_f(r['accuracy_on_covered'])} |")
    parts += [
        "",
        f"Test ECE (calibrated): {_f(cal['calibrated_test']['ece_top_label'])}; "
        f"native LogReg probabilities: {_f(cal['uncalibrated_native_logreg_test']['ece_top_label'])}.",
        "",
        "## Part II - SYNTHETIC demo data (labels defined by the generator; says nothing about real accuracy)",
        "",
        experiment_table(
            "synthetic_category_DEMO", "Category (SYNTHETIC)", "Ablation outcomes mirror the generator design."
        ),
        experiment_table(
            "synthetic_team_DEMO", "Team assignment (SYNTHETIC)", "Deployed demo team model: text/logreg."
        ),
    ]
    print("\n".join(parts))


if __name__ == "__main__":
    main()
