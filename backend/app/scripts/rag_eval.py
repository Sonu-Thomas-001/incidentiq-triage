"""Measured offline evaluation of the retrieval-augmented assignment.

    python -m app.scripts.rag_eval [--gemini-sample 40] [--seed 377]

Protocol (no training, no tuning, so no validation split is needed):
- Every indexed ServiceNow incident is a query in turn; it is excluded from its own neighbours
  (leave-one-out) while all other indexed incidents remain retrievable.
- Results are reported separately by origin: `native` (records that existed in the instance) and
  `seed_script` (template-generated by `servicenow-seed`; SYNTHETIC, so scores mostly show that the
  method recovers the generator's mapping).
- Rows: majority baseline, similarity-weighted k-NN vote (whole origin subset) and the deployed
  Gemini decision (seeded random sample; costs one Gemini call per ticket).
Files are written to EVALUATION_DIR in the format served by GET /models/evaluations.
"""

from __future__ import annotations

import argparse
import json
import random
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np

from app.core.config import get_settings
from app.services import rag_service


def _round(x: float) -> float:
    return round(float(x), 4)


def metrics(
    y_true: list[str], y_pred: list[str], ranked: list[list[str]] | None = None
) -> dict[str, Any]:
    labels = sorted(set(y_true) | set(y_pred))
    idx = {label: i for i, label in enumerate(labels)}
    cm = [[0] * len(labels) for _ in labels]
    for t, p in zip(y_true, y_pred, strict=True):
        cm[idx[t]][idx[p]] += 1
    per_class: dict[str, dict[str, Any]] = {}
    for label in labels:
        i = idx[label]
        tp = cm[i][i]
        fp = sum(cm[r][i] for r in range(len(labels))) - tp
        fn = sum(cm[i]) - tp
        prec = tp / (tp + fp) if tp + fp else 0.0
        rec = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
        per_class[label] = {
            "precision": _round(prec),
            "recall": _round(rec),
            "f1": _round(f1),
            "support": tp + fn,
        }
    n = len(y_true)
    present = [p for p in per_class.values() if p["support"] > 0]
    macro = {
        k: _round(sum(p[k] for p in present) / len(present)) for k in ("precision", "recall", "f1")
    }
    weighted_f1 = sum(p["f1"] * p["support"] for p in present) / n
    top1 = _round(sum(t == p for t, p in zip(y_true, y_pred, strict=True)) / n)
    topk: dict[str, float] = {"1": top1}
    if ranked is not None:
        topk["3"] = _round(sum(t in r[:3] for t, r in zip(y_true, ranked, strict=True)) / n)
    return {
        "n": n,
        "accuracy": top1,
        "macro": macro,
        "weighted": {"f1": _round(weighted_f1)},
        "topk": topk,
        "per_class": per_class,
        "confusion_matrix": {"labels": labels, "matrix": cm},
    }


def _load() -> dict[str, Any]:
    col = rag_service._collection(get_settings())
    got = col.get(include=["embeddings", "metadatas", "documents"])
    emb = np.asarray(got["embeddings"], dtype=np.float64)
    emb /= np.linalg.norm(emb, axis=1, keepdims=True)
    return {"ids": got["ids"], "emb": emb, "meta": got["metadatas"], "docs": got["documents"]}


def _vote(sims: np.ndarray, labels: list[str], k: int) -> dict[str, float]:
    weights: dict[str, float] = defaultdict(float)
    for j in np.argsort(-sims)[:k]:
        if labels[j]:
            weights[labels[j]] += max(float(sims[j]), 0.0)
    total = sum(weights.values())
    return {a: w / total for a, w in weights.items()} if total else {}


def _knn_predictions(data: dict[str, Any], queries: list[int], field: str, k: int):
    labels = [m.get(field) or "" for m in data["meta"]]
    sim = data["emb"] @ data["emb"].T
    y_true, y_pred, ranked = [], [], []
    for i in queries:
        if not labels[i]:
            continue
        s = sim[i].copy()
        s[i] = -1.0  # leave one out
        shares = _vote(s, labels, k)
        if not shares:
            continue
        order = sorted(shares, key=lambda a: -shares[a])
        y_true.append(labels[i])
        y_pred.append(order[0])
        ranked.append(order)
    return y_true, y_pred, ranked


def _majority(y_true: list[str], pool: list[str]) -> dict[str, Any]:
    label = Counter(pool).most_common(1)[0][0]
    return metrics(y_true, [label] * len(y_true))


def _gemini_rows(data: dict[str, Any], queries: list[int], sample: int, seed: int):
    rng = random.Random(seed)
    chosen = rng.sample(queries, min(sample, len(queries)))
    out: dict[str, tuple[list[str], list[str], list[float]]] = {
        "category": ([], [], []),
        "team": ([], [], []),
    }
    abstained = 0
    for i in chosen:
        res = rag_service.predict(data["docs"][i], "", exclude_id=data["ids"][i])
        if res["status"] != "MODEL":
            abstained += 1
            continue
        for task in ("category", "team"):
            o = res["outputs"][task]
            truth = data["meta"][i].get(task)
            if o.get("available") and truth:
                out[task][0].append(truth)
                out[task][1].append(o["label"])
                out[task][2].append(o["confidence"])
    return out, len(chosen), abstained


def _selective(y_true: list[str], y_pred: list[str], conf: list[float]) -> list[dict[str, Any]]:
    rows = []
    for t in (0.0, 0.6, 0.7, 0.8, 0.9, 1.0):
        keep = [i for i, c in enumerate(conf) if c >= t]
        rows.append(
            {
                "threshold": t,
                "coverage": _round(len(keep) / len(conf)) if conf else None,
                "accuracy": (
                    _round(sum(y_true[i] == y_pred[i] for i in keep) / len(keep)) if keep else None
                ),
                "n": len(keep),
            }
        )
    return rows


def run(sample: int, seed: int, out_dir: Path) -> list[Path]:
    s = get_settings()
    data = _load()
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for origin, provenance in (("native", "real"), ("seed_script", "synthetic-template")):
        queries = [i for i, m in enumerate(data["meta"]) if m.get("origin") == origin]
        if len(queries) < 10:
            continue
        gem, sampled, abstained = _gemini_rows(data, queries, sample, seed)
        for task, name in (("category", "category"), ("team", "assignment_group")):
            y, p, ranked = _knn_predictions(data, queries, task, s.rag_top_k)
            if not y:
                continue
            pool = [m.get(task) or "" for m in data["meta"] if m.get(task)]
            gy, gp, gc = gem[task]
            models: dict[str, Any] = {
                "retrieval_vote_knn": {
                    "feature_set": f"{s.embedding_model} ({s.embedding_dimensions}-d, redacted text)",
                    "algorithm": f"similarity-weighted k-NN vote, k={s.rag_top_k}",
                    "val_macro_f1": None,
                    "test": metrics(y, p, ranked),
                }
            }
            if gy:
                models["gemini_rag_decision"] = {
                    "feature_set": f"retrieved neighbours + {s.gemini_model}",
                    "algorithm": "LLM chooses among indexed labels given similar incidents",
                    "val_macro_f1": None,
                    "test": metrics(gy, gp),
                }
            note = (
                "Template-generated by servicenow-seed: SYNTHETIC. Scores show recovery of the "
                "generator's mapping, not real-world performance."
                if origin == "seed_script"
                else "Records that existed in the instance (labels = assignment_group / category)."
            )
            experiment = {
                "experiment": f"rag_{name}_{origin}",
                "generated_at": datetime.now(UTC).isoformat(),
                "dataset": {
                    "source": "ServiceNow Personal Developer Instance (incident table)",
                    "provenance": provenance,
                    "origin": origin,
                    "n_queries": len(y),
                    "index_size": len(data["ids"]),
                    "note": note,
                },
                "split": "leave-one-out over the index (no training, no tuning)",
                "seed": seed,
                "protocol": (
                    f"k-NN row: all {len(y)} {origin} tickets. Gemini row: seeded random sample of "
                    f"{sampled} tickets ({abstained} abstained: no sufficiently similar incident)."
                ),
                "baselines": {"majority": {"val_macro_f1": None, "test": _majority(y, pool)}},
                "models": models,
                "selected_by_validation": None,
                "deploy_choice": "gemini_rag_decision" if gy else "retrieval_vote_knn",
                "selective_accuracy_gemini": _selective(gy, gp, gc) if gy else None,
                "embedding_model": s.embedding_model,
                "decision_model": s.gemini_model,
            }
            path = out_dir / f"rag_{name}_{origin}.json"
            path.write_text(json.dumps(experiment, indent=2), encoding="utf-8")
            written.append(path)
    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--gemini-sample", type=int, default=40, help="tickets per origin for Gemini")
    ap.add_argument("--seed", type=int, default=377)
    args = ap.parse_args()
    for path in run(args.gemini_sample, args.seed, Path(get_settings().evaluation_dir)):
        print("wrote", path)


if __name__ == "__main__":
    main()
